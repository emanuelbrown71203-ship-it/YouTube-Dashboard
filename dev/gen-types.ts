// Writes src/lib/database.types.ts from a local database that has the migrations applied,
// so every table and column name the app uses is checked by the TypeScript compiler.
//   npx tsx dev/gen-types.ts [database-url]

import { writeFileSync } from "node:fs";
import postgres from "postgres";

const url = process.argv[2] ?? "postgresql://ytdev:ytdev@localhost:5432/yttest";
const sql = postgres(url, { max: 1, onnotice: () => {} });

const TS: Record<string, string> = {
  text: "string", uuid: "string", date: "string", "timestamp with time zone": "string", boolean: "boolean",
  bigint: "number", integer: "number", smallint: "number", numeric: "number", "double precision": "number",
  jsonb: "Json", json: "Json", interval: "string", void: "undefined",
};
const tsType = (dataType: string, udt: string) =>
  dataType === "ARRAY" ? `${TS[{ _text: "text" }[udt] ?? "text"]}[]` : (TS[dataType] ?? "unknown");

const columns = await sql`
  select c.table_name, c.column_name, c.data_type, c.udt_name, c.is_nullable, c.column_default, c.is_identity,
         t.table_type
  from information_schema.columns c
  join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
  where c.table_schema = 'public' and c.table_name like 'yt\_%'
  order by c.table_name, c.ordinal_position`;

const functions = await sql`
  select p.proname as name, pg_get_function_arguments(p.oid) as args, pg_get_function_result(p.oid) as result
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.proname like 'yt\_%' and p.prorettype <> 'trigger'::regtype
  order by p.proname`;

const tables = new Map<string, { view: boolean; cols: typeof columns }>();
for (const c of columns) {
  const entry = tables.get(c.table_name) ?? { view: c.table_type === "VIEW", cols: [] as unknown as typeof columns };
  entry.cols.push(c);
  tables.set(c.table_name, entry);
}

const block = (name: string, view: boolean, cols: typeof columns) => {
  const row = cols.map((c) => `          ${c.column_name}: ${tsType(c.data_type, c.udt_name)}${view || c.is_nullable === "YES" ? " | null" : ""};`).join("\n");
  if (view) return `      ${name}: {\n        Row: {\n${row}\n        };\n        Relationships: [];\n      };`;
  const write = (optionalAll: boolean) => cols.map((c) => {
    const optional = optionalAll || c.is_nullable === "YES" || c.column_default !== null || c.is_identity === "YES";
    return `          ${c.column_name}${optional ? "?" : ""}: ${tsType(c.data_type, c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};`;
  }).join("\n");
  return `      ${name}: {\n        Row: {\n${row}\n        };\n        Insert: {\n${write(false)}\n        };\n        Update: {\n${write(true)}\n        };\n        Relationships: [];\n      };`;
};

const fn = (f: (typeof functions)[number]) => {
  const args = String(f.args).split(",").map((a) => a.trim()).filter(Boolean).map((a) => {
    const m = /^(\w+) (.+?)( DEFAULT .+)?$/.exec(a)!;
    return `${m[1]}${m[3] ? "?" : ""}: ${TS[m[2]] ?? "unknown"}${m[3]?.includes("NULL") ? " | null" : ""}`;
  });
  return `      ${f.name}: {\n        Args: ${args.length ? `{ ${args.join("; ")} }` : "Record<PropertyKey, never>"};\n        Returns: ${TS[f.result] ?? "unknown"};\n      };`;
};

const out = `// Generated by dev/gen-types.ts from the migrations. Do not edit by hand.

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
${[...tables].filter(([, t]) => !t.view).map(([n, t]) => block(n, false, t.cols)).join("\n")}
    };
    Views: {
${[...tables].filter(([, t]) => t.view).map(([n, t]) => block(n, true, t.cols)).join("\n")}
    };
    Functions: {
${functions.map(fn).join("\n")}
    };
    Enums: Record<string, never>;
    CompositeTypes: Record<string, never>;
  };
};

type Public = Database["public"];
export type Row<T extends keyof Public["Tables"]> = Public["Tables"][T]["Row"];
export type ViewRow<T extends keyof Public["Views"]> = Public["Views"][T]["Row"];
export type Insert<T extends keyof Public["Tables"]> = Public["Tables"][T]["Insert"];
export type Update<T extends keyof Public["Tables"]> = Public["Tables"][T]["Update"];
`;
writeFileSync(new URL("../src/lib/database.types.ts", import.meta.url), out);
await sql.end();
console.log(`wrote ${tables.size} tables/views and ${functions.length} functions`);
